export function buildLeadsColumns(customFields = []) {
  const dynamicCustomCols = (customFields || []).map((f) => ({
    id: f.key,
    header: f.label,
    accessorKey: f.key,
    group: "Custom Fields",
    filterable: true,
    defaultVisible: false,
    cellType: f.type === "number" ? "number" : "text",
    width: 140,
    minWidth: 120,
  }));

  return [...BASE_LEADS_COLUMNS, ...dynamicCustomCols];
}

