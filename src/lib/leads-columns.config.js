/**
 * Builds the complete list of column definitions by programmatically appending
 * tenant-specific custom fields (Columns 58-63) to the base 57 columns.
 * Every column is visible by default so users can view the full depth of data.
 */
export function buildLeadsColumns(customFields = getTenantCustomFields()) {
  const dynamicCustomCols = (customFields || []).map((f) => ({
    id: f.key,
    header: f.label,
    accessorKey: f.key,
    group: "Custom Fields",
    filterable: true,
    defaultVisible: true,
    cellType: f.type === "number" ? "number" : "text",
  }));

  return [...BASE_LEADS_COLUMNS, ...dynamicCustomCols];
}

